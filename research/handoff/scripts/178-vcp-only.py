NUM = re.compile(r"\*\*([+-]\d+\.\d+)%p\*\*\s*(?:\[([+-]\d+\.\d+),\s*([+-]\d+\.\d+)\])?")


def grab(path, pat, nth):
    """그 줄에서 «nth 번째» `**±x.xxx%p**` 와 «바로 뒤» CI 를 꺼낸다."""
    rx = re.compile(pat)
    for ln in path.read_text(encoding="utf-8").split("\n"):
        if not rx.search(ln):
            continue
        hits = NUM.findall(ln)
        if len(hits) < nth:
            continue
        mu, lo, hi = hits[nth - 1]
        if not lo:
            m2 = re.search(r"\[([+-]\d+\.\d+),\s*([+-]\d+\.\d+)\]", ln)
            if m2:
                lo, hi = m2.group(1), m2.group(2)
        return float(mu), (float(lo) if lo else None), (float(hi) if hi else None), ln
    return None


def cell(lo, hi):
    if lo is None:
        return "—"
    if lo >= DELTA:
        return "1"
    if hi <= -DELTA:
        return "2"
    if lo > 0:
        return "4a" if hi <= DELTA else "4b"
    if hi < 0:
        return "4a" if lo >= -DELTA else "4b"
    return "5"


