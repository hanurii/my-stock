"""두뇌 세션 검산(+2.40 vs −1.78 부호 반대)의 «원인»을 짚는다. 새 자료 없음."""
W=[("닷컴 1999~2001",3.0,22.56,1.2),("2002~2017",15.7,-2.57,1.5),("2018~2026",8.7,4.39,1.1)]
tot=sum(y for _,y,_,_ in W)
wavg=sum(y*d for _,y,d,_ in W)/tot
lavg=sum(y*L for _,y,_,L in W)/tot
print("="*76); print("A. 왜 «기간 가중 +2.40%p» 와 «전체 −1.78%p» 의 부호가 반대인가"); print("="*76)
for lab,y,d,L in W: print("  %-16s %5.1f년  차 %+7.2f%%p   지수 배수 **%.1f배**" % (lab,y,d,L))
print("  " + "-"*62)
print("  기간 가중 평균 차          **%+.2f%%p**   ·  기간 가중 «배수» **%.2f배**" % (wavg,lavg))
print("  문서의 「전체」 줄          **%+.2f%%p**   ·  그 줄의 배수      **2.0배**" % (-1.78))
print()
print("  ⇒ **역설이 아니다.** 창별 줄들은 지수를 «평균 %.2f배»만 올리고," % lavg)
print("     전체 줄은 «2.0배» 올린다 — **더 센 상대와 붙은 것**이라 우리가 진다")
print("  ⇒ 두 수는 «다른 상대»와의 값이다. 이어 붙이기가 «정의상 불가»인 것도 같은 이유")
print()
print("="*76); print("B. 🚨 결정적 — 창별 배수(1.2/1.5/1.1)는 «그 창을 알아야» 정한다"); print("="*76)
print("  1999년 1월에 「앞으로 3년은 닷컴이니 1.2배로」를 «고를 수» 없다")
print("  ⇒ **창별 네 줄은 «집행 불가»다.** 「국면이 가른다」와 «같은 병» — 사후에만 이름이 붙는다")
print("  ⇒ 집행 가능한 줄은 **「전체 2.0배」 하나**뿐이다")
print()
print("="*76); print("C. ✅ 그런데 답은 110 §2 가 아니라 110 §1 에 있다"); print("="*76)
print("  110 §2 의 상대  SPY+200일선 ×레버리지  →  **손잡이가 «고른» 것**(200일선) = «전략»")
print("  110 §1 의 상대  **QQQ 그냥 보유**       →  **손잡이 0 개** = 유일한 «기준»")
print("     수익÷낙폭   우리 **0.204**  vs  QQQ **0.128**  =  **우리가 %.2f배**" % (0.204/0.128))
print("     150 자로 재도 우리 8.47/35.4=**0.239** vs QQQ 9.70/83.0=**0.117** = **%.2f배**" % ((8.47/35.4)/(9.70/83.0)))
print("  ⇒ **두 자 전부에서 우리가 «기준»을 위험 대비로 이긴다** → 「덜 아프다」는 «확실»(QQQ 대비 한정)")
