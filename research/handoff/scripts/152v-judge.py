"""152 판정 — ① 배당 비대칭이 «정말» 작은가(내가 안 재고 적은 값) ② 세금 절의 격 ③ 표 검산."""
print("="*80); print("A. 🚨 배당 비대칭 — 「격차가 «좁아질 뿐»」은 내가 «안 재고» 적었다"); print("="*80)
GAP=1.23
for inv,y,lab in ((0.94,0.2,"성장주 배당 0.2% · 투자율 94%"),(0.94,0.5,"0.5%"),(0.94,1.0,"1.0%(시장 평균급)")):
    loss=inv*y
    print("  %-34s 우리 쪽 «빠진» 배당 ≈ **%.2f%%p/년**  =  격차 1.23%%p 의 **%.0f%%**"
          % (lab, loss, 100*loss/GAP))
print()
print("  ⇒ **격차의 15~76%** 자리다. 「좁아질 뿐」이 아니라 **«상당 부분»일 수 있다**")
print("  ⛔ 내가 «크기»를 안 재고 「좁아질 뿐」이라 적었다 — **유형 44 의 다섯 번째**")
print("  ✅ 적을 말: **「안 쟀다 — 크기 미상, 방향은 우리에게 «유리»」**")

print(); print("="*80); print("B. 세금 절 — «변명»인가 «발견»인가 가르는 시험"); print("="*80)
print("  물음: **그 요소가 «우리 설계의 «결과»»인가, «외부 사정»인가?**")
print("     외부라면  →  「~만 없으면」은 **반사실** = 변명")
print("     설계라면  →  **«고칠 수 있는 것»의 이름** = 발견")
print()
print("  세전 −0.05%p → 세후 −1.23%p.  원인 = **27년간 실현 644번 vs QQQ 1번**")
print("  ⇒ 실현 횟수는 **+20/−10 «청산 규칙»이 만든 것** = **우리 설계의 결과** → **«발견»이다** ✅")
print("  ★ 적을 말: 「세금이 격차의 96%」가 아니라")
print("             **「우리 «청산 규칙»이 세금 시점을 통해 연 1.2%p 를 쓴다」**")
print()
print("  🚨 그런데 딸림 경고 — **기존 청산 결론이 «세전»이었다면 그 자는 이 자료에서 «틀린 자»다**")
print("     (「55변형 중 현행을 이긴 것 0개」·「조기청산 0승」이 세전이면, 세후로는 «다를 수 있다»)")
print("     ⇒ **확인 대상**이지 내가 «결론»을 내는 자리가 아니다")

print(); print("="*80); print("C. 표 검산 — SD 를 역산해 「필요 년수」와 맞는가"); print("="*80)
from math import sqrt
rows=[("우리−SPY 전체",2.09,9.64,27,2.056,1025),("우리−QQQ 전체",-0.80,13.38,27,2.056,13462),
      ("우리−SPY 표본밖",0.22,9.99,15,2.145,52369),("우리−QQQ 표본밖",-3.31,13.94,15,2.145,453)]
for lab,g,hw,n,t,yr in rows:
    sd=hw*sqrt(n)/t; need=((1.959964+0.841621)*sd/abs(g))**2
    print("  %-18s 역산 SD **%5.1f%%p**  →  필요 년수 **%8.0f**   (문서 %6d)  %s"
          % (lab,sd,need,yr,"✅" if abs(need-yr)/yr<0.12 else "🚨 어긋남"))
print()
print("  ⇒ 넷 다 맞는다. **표본 밖 우리−QQQ 의 453년이 «제일 작은» 수** — 그래도 있는 것의 **29배**")
