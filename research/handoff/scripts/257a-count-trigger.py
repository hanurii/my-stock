# -*- coding: utf-8 -*-
r"""257a - **조건이 «걸리는» 거래가 «몇» 건인가 — 팔을 «짓기» «전»**  (조사 세션 2026-09-10)

  🚨 **검증 조건 ①**(유형 95) — **「질 수가 «없는» 팔」을 «판»으로 «세면» «안** 된다.

  📐 **자**: 조건 = 「«미실현» 수익 ≥ «위험노출» × N」
     위험노출 = **`a × stop/100`**(우리 정의 · `257-PRE` §④에 「«우리» 것」으로 적음)
     ⇒ **수익률로는 「N × stop%」** ⇒ **stop = 10 이므로 N×10%**
     ⇒ **Ⓑ2 = ＋20% · Ⓑ4 = ＋40% · Ⓑ6 = ＋60%**  ·  **우리 목표 = ＋30%**

  🔎 **세는 것**: 「«결착» 봉 «앞»의 «어느» 봉에서 고가가 문턱에 «닿았나」
     ⇒ **닿은 적이 «없으면» 조건이 «영원히» 불발** ⇒ **팔이 ① 과 «똑같아진다** ⇒ **«죽은» 팔**

  ⛔ **팔을 «짓지» «않았다** · ⛔ **성적을 «내지» «않았다** — **«건수»만**

실행: PYTHONIOENCODING=utf-8 PYTHONUTF8=1 python research/handoff/scripts/257a-count-trigger.py
"""
from __future__ import annotations

import importlib.util as _u
import sys
import time
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
P = print
BQ = chr(96)
F3 = BQ * 3
HERE = Path(__file__).resolve().parent

NS = (2, 3, 4, 6)          # ⛔ 3 은 «경계»를 «보이려고** 넣었다(＋30 = 목표와 «같은» 자리)


def _load(nm, fn):
    s = _u.spec_from_file_location(nm, HERE / fn)
    m = _u.module_from_spec(s)
    sys.modules[nm] = m
    s.loader.exec_module(m)
    return m


m201d = _load("m201d", "201d-rs-threshold.py")
r91 = m201d.r91


def main():  # noqa: C901
    P("# 257a - **조건이 «걸리는» 거래가 «몇» 건인가**(팔을 «짓기» «전»)")
    P("")
    P("> 조사 세션 · " + BQ + "research/handoff/scripts/257a-count-trigger.py" + BQ
      + " · **문서는 이 출력 그 자체**(유형 48)")
    P("> ⛔ **팔을 «짓지» «않았다** · ⛔ **성적을 «내지» «않았다** — **«건수»만**")
    P("")
    P(F3)
    P("🚨 **검증 조건 ①**(유형 95) — **「질 수가 «없는» 팔」을 «판»으로 «세면» «안** 된다")
    P("")
    P("📐 조건 = 「«미실현» 수익 ≥ «위험노출» × N」 · 위험노출 = **`a × stop/100`**")
    P("   ⇒ **수익률로는 「N × stop%%」** ⇒ **stop = %.0f 이므로**:" % m201d.STOP)
    for n in NS:
        P("      **N=%d → ＋%.0f%%**%s" % (n, n * m201d.STOP,
                                           "   ← 🚨 **목표(＋%.0f%%) «위»**" % m201d.TARGET
                                           if n * m201d.STOP > m201d.TARGET else ""))
    P("   **우리 목표 = ＋%.0f%%**(`91:87`)" % m201d.TARGET)
    P(F3)
    P("")
    P("---")
    P("")

    P("(정본 짝을 «짓는» 중 …)", flush=True)
    t0 = time.time()
    pairs, miss = m201d.build_pairs(m201d.CANON)
    if pairs is None:
        P("🚨 경로 «없음»: %s" % miss[:3])
        return 1

    hit = {n: 0 for n in NS}
    hit_res = {n: 0 for n in NS}       # 🔴 «틀린» 자 — «결착»일 앞(첫 판에 쓴 것)
    tot = 0
    for t, p in pairs:
        r = t["masks"][()]
        d, h = p["d"], p["h"]
        rd = r["resolve_date"]
        ri = d.index(rd) if (rd and rd in d) else len(d) - 1
        # ★★ **«첫» 청산일**(목표 도달 «또는» 손절) — **«거기»까지가 조건이 «사는» 구간**
        exs = r["exits"]
        fd = exs[0][0] if exs else rd
        fi = d.index(fd) if (fd and fd in d) else ri
        epx = t["entry_px"]
        tot += 1
        for n in NS:
            thr = epx * (1.0 + n * m201d.STOP / 100.0)
            if any(h[i] is not None and h[i] >= thr for i in range(0, fi)):
                hit[n] += 1
            if any(h[i] is not None and h[i] >= thr for i in range(0, ri)):
                hit_res[n] += 1
    el = time.time() - t0

    P("")
    P("# 🔴🔴 **«자»를 «고쳤다** — ⛔ **결과를 «보고» «갈은» 것이 «아니라 «자»가 «틀렸다**")
    P("")
    P(F3)
    P("   ⛔ **«처음» 쓴 자**: 「**«결착»일 «앞**»에 닿았나」")
    P("   ✅ **«고친» 자**: 「**«첫» 청산일(목표 도달 «또는» 손절) «앞**»에 닿았나」")
    P("")
    P("   ★ **왜 «처음»부터 틀렸나 — «코드»에 있다**")
    P("      📄 `pyr_trigger.py:192` `s2 = max(a, min(seg))` ＋ `:166` `FLOOR_BE = True`")
    P("      ⇒ **목표에 «닿으면» `_phase2` 가 «이미» «본전(a)» 바닥을 «깐다**")
    P("      ⇒ ⇒ ★★ **「조건부 본전」이 «할» 일이 «남아» 있는 구간은 **「진입 ~ «첫» 청산 «전»」**뿐**이다")
    P("      ⇒ **«결착»일은 «추격»이 «끝난» 날**이라 — **목표 «뒤» 구간을 «통째»로 «세고» 있었다**")
    P("")
    P("   🚨 **그래서 «두» 수를 «둘» 다 «적는다** — ⛔ **«틀린» 수를 «지우지» «않는다**")
    P(F3)
    P("")

    P("")
    P("# 🔢 **「조건이 «걸리는» 거래」 — «건수**")
    P("")
    P("| N | 문턱(수익률) | 목표 «위»인가 | ✅ **«첫» 청산 «앞**(고친 자) | 비율 | 🔴 «결착» 앞(틀린 자) |")
    P("|---:|---:|:--|---:|---:|---:|")
    for n in NS:
        thr = n * m201d.STOP
        P("| **%d** | **＋%.0f%%** | %s | **%s** | **%.2f%%** | %s |"
          % (n, thr, "🚨 **«위»**" if thr > m201d.TARGET else "✅ 아래",
             format(hit[n], ","), 100.0 * hit[n] / max(1, tot), format(hit_res[n], ",")))
    P("")
    P(F3)
    P("   거래 **%s** · 💰 실측 **%.1f분**" % (format(tot, ","), el / 60.0))
    P("")
    dead = [n for n in NS if hit[n] == 0]
    P("   ⇒ **조건이 «한» 번도 «안** 걸리는 N = %s"
      % ("**%s**" % ", ".join(str(x) for x in dead) if dead else "**«없음»**"))
    if dead:
        P("      ⇒ ★★★ **«그» 팔들은 ① 과 «똑같아진다** ⇒ **«죽은» 팔**")
        P("      ⇒ ✅ **「양성 대조」로 «부르고» «판정»에서 «뺀다**")
        P("         (**`257-PRE` §비용의 「배수를 «아주» 크게」 대조가 «이미» «여기» 있다**)")
    P(F3)
    P("")
    P("---")
    P("")
    P("# 🚨 **⇒ 「어긋남」 «자체»가 «발견»이다**")
    P("")
    P(F3)
    P("   🔎 목표 ＋%.0f%% · stop %.0f 에서 **«걸릴» 수 «있는» 배수는 «N < %.1f»**"
      % (m201d.TARGET, m201d.STOP, m201d.TARGET / m201d.STOP))
    P("   🚨 그런데 그건 **원전 «범위»(`tm:39` 2~6) 의 «아래»끝 «언저리»뿐**이다")
    P("")
    P("   ⇒ ★★★ **「원전의 «배수 범위»와 «우리» 목표(＋%.0f%%)가 «양립»하지 «않는다」**"
      % m201d.TARGET)
    P("      ⇒ **`256` 의 단서와 «같은» 종류**다(원전은 「«스윙»」·「위험 대비 보상 «반전»」인데")
    P("        우리는 「＋%.0f%% «목표»」) — **«격자»가 «아니라» «전제»가 어긋난다**" % m201d.TARGET)
    P(F3)
    P("")
    P("## ⚖️ **격자를 «어떻게» 할 것인가 — «둘» 다 적는다**(⛔ **«말없이» «옮기지» «않는다**)")
    P("")
    P(F3)
    P("| 길 | 격자 | «값»은 «누구» 것인가 | 무슨 «값»이 되나 |")
    P("|---|---|---|---|")
    P("| **㉮ 원전 «범위»를 «지킨다**(2·4·6) | Ⓑ2 · Ⓑ4 · Ⓑ6 | ✅ **범위는 원전 것** | "
      "🚨 **Ⓑ4·Ⓑ6 이 «죽은» 팔** ⇒ **판정은 «사실상» Ⓑ2 «하나»** ＋ **양성 대조 «둘»** |")
    P("| **㉯ 「걸릴 수 «있는» 범위」로 «옮긴다**(예 1·1.5·2) | Ⓑ1 · Ⓑ1½ · Ⓑ2 | "
      "🔴 **1·1.5 는 «원전» 범위 «밖» = «우리»가 «고른» 수** | ✅ 셋 다 «산다** |")
    P("")
    P("   🔴 **«내» 권함**(⛔ **결정은 «두뇌»·«검증»**): **㉮**")
    P("      까닭 ① **㉯ 로 가면 「우리가 «고른» 수」가 «둘» «늘고** — **`256` 의 «값»("
      "「원전이 «준» 수만 썼다」)을 «잃는다**")
    P("      까닭 ② **㉮ 의 「죽은 팔 «둘»」은 «손해»가 «아니라 «양성 대조»**다 —")
    P("         **「복사본이 원본과 «같은가»」를 «공짜»로 «검산**해 준다")
    P("      까닭 ③ ★ **「원전 범위와 우리 목표가 «양립» 안 한다」가 «이» 판의 «소득»**이고,")
    P("         **㉯ 로 옮기면 «그» 소득이 «가려진다**")
    P("")
    P("   ⛔ **㉮ 로 가면 «못» 쓸 말**: 「원전 «범위»를 «다» 재 봤다」 ✗ —")
    P("      **«실제»로 «잰» 것은 **N=2 «하나»**다")
    P(F3)
    P("")
    P("# ⚠️ **이 판이 «못** 한 것**")
    P("")
    P(F3)
    P("⛔ ① **「닿았다」는 «고가» 기준**이다 — **«장중»에 닿아도 «종가»엔 «내려올** 수 있다")
    P("     ⇒ **원전이 「수익이 «되면»」이라 했지 「«종가»가」라 «안** 했다 ⇒ **«고가»로 «읽었다**(우리 «선택»)")
    P("⛔ ② **`a`(평균단가)를 `entry_px` 로 «잡았다** — `shares=(1.0,)` 라 **트랜치가 «하나»**여서다")
    P("⛔ ③ **「결착 «앞»」으로 «셌다** — **결착 «봉» «그날»에 «닿는» 경우는 «뺐다**")
    P("     ⇒ **그날은 목표·손절이 «이미» 걸린다** ⇒ ⛔ **그래도 «경계»라 «적어» 둔다**")
    P("⛔ ④ **성적을 «안** 냈다 — **«건수»뿐**이다")
    P(F3)
    P("")
    P("⛔ **커밋은 두뇌 몫입니다.**")
    return 0


