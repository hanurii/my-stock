# -*- coding: utf-8 -*-
"""조사 세션의 「3승 1패」를 «시간»으로 다시 센다. 110:14~18 표만 씀 — 새 자료 없음."""
Y={"닷컴 1999~2001":3.0,"2002~2017":15.7,"2018~2026":8.7}
R={"우리":{"닷컴 1999~2001":1.036,"2002~2017":0.069,"2018~2026":0.831},
   "SPY 그냥":{"닷컴 1999~2001":0.093,"2002~2017":0.128,"2018~2026":0.452},
   "QQQ 그냥":{"닷컴 1999~2001":0.145,"2002~2017":0.176,"2018~2026":0.576}}
FULL={"우리":0.204,"SPY 그냥":0.156,"QQQ 그냥":0.128}
T=sum(Y.values())

print("="*76); print("A. 🚨 「3승 1패」는 못 센다 — «전체»가 나머지 셋을 «담고» 있다"); print("="*76)
print("  타일: 3.0 + 15.7 + 8.7 = **%.1f년** = 전체.  ⇒ 네 창은 «독립 시행 4개»가 아니다" % T)
print("  ⇒ 셀 수 있는 건 **조각 셋**: 우리가 «지는» 조각 하나 = **2002~2017**")
print("     그 조각의 길이 **15.7년 = 전체 시간의 %.1f%%**" % (100*Y["2002~2017"]/T))
print("  ⇒ **「3승 1패」가 아니라 「시간의 %.0f%%에서 진다」** 가 맞는 셈법" % (100*Y["2002~2017"]/T))

print(); print("="*76); print("B. 그런데 «전체» 창에서는 우리가 이긴다 — 어디서 오나"); print("="*76)
for k in ("우리","QQQ 그냥"):
    parts=" · ".join("%s **%.3f**"%(w.split()[0],R[k][w]) for w in Y)
    print("  %-8s 조각: %s   →  **전체 %.3f**" % (k,parts,FULL[k]))
print()
print("  🚨 QQQ 는 «전체(0.128)»가 «조각 셋 «전부»»보다 낮다(0.145·0.176·0.576)")
print("     ⇒ 조각 안에 없는 «걸친 낙폭»(2000~2002 붕괴 −83%)이 전체를 끌어내린다")
print("  ⇒ **「전체 27.4년 위험 대비 1.59배」의 상당 몫이 «한 사건»(닷컴 붕괴)에서 온다**")
print("     ⚠️ 계열 없이 정확히 못 쪼갠다 — «방향»만 적을 것")

print(); print("="*76); print("C. ✅ 그래서 적을 수 있는 문장"); print("="*76)
print("  ✅ 「위험 대비로는 QQQ 그냥 보유를 이긴다(전체 27.4년 **1.59배**)」")
print("  ✅ 「**단 «한 번도 안 본» 2002~2017 에서는 뒤집힌다** — 우리 0.069 vs QQQ 0.176 · SPY 0.128」")
print("  ✅ 「그 창이 **전체 시간의 %.0f%%**이고, 이기는 몫은 닷컴 3년(전체의 11%%)에 몰려 있다」" % (100*15.7/27.4))
print("  ⛔ 「3승 1패」 — 창이 «겹친다». ⛔ 「두 자 전부에서 이긴다」 — «한 창»의 수였다")
