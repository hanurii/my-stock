    P("")
    P("---")
    P("")
    P("# 1. **MDE — 짝마다 · «전»/«후»**")
    P("")
    P("| 짝 | «전» SD | **«후» SD** | c | «전» MDE(최대통계) | **«후» MDE(최대통계)** | «후» \\|효과\\| | 관측÷MDE |")
    P("|---|---:|---:|---:|---:|---:|---:|---:|")
    old, new = [], []
    for nm, e0, sd0, c, e1, t1, _src in ROWS:
        sd1 = e1 / t1 if t1 else float("nan")
        m0 = (c + Z80) * sd0
        m1 = (c + Z80) * sd1
        old.append(m0)
        new.append(m1)
        P("| **%s** | %.2f | **%.3f** | %.2f | %.2f%%p | **%.2f%%p** | %.3f | %.2f |"
          % (nm, sd0, sd1, c, m0, m1, e1, e1 / m1))
    P("")
    P(F3)
    P("   «전»  최소 **%.2f%%p** · 중앙 **%.2f%%p** · 최대 **%.2f%%p**"
      % (min(old), st.median(old), max(old)))
    P("   **«후»  최소 %.2f%%p · 중앙 %.2f%%p · 최대 %.2f%%p**"
      % (min(new), st.median(new), max(new)))
    P("")
    nb0 = sum(1 for m in old if m <= DELTA)
    nb1 = sum(1 for m in new if m <= DELTA)
    P("   ★ **Δ = %.2f%%p 를 «가릴 수» 있는 짝**  —  «전» **%d / %d**  ·  **«후» %d / %d**"
      % (DELTA, nb0, len(old), nb1, len(new)))
    P("")
    nup = sum(1 for a, b in zip(old, new) if b > a)
    P("   ★ **여덟 짝 «중» %d** 에서 MDE 가 «올랐다** (내려간 짝 **%d**)" % (nup, len(old) - nup))
    P("   ⛔ **「8 중 %d」을 «증거 세기»로 «읽지» 않는다** — **여덟이 «독립»이 «아니다**(유형 **99**)" % nup)
    P("     («같은» 계보 `183`·`184` · «같은» 자료)")
    P(F3)
    P("")
    P("---")
    P("")
    P("# 2. ★★★ **「연구의 답」에 «쓸» 수 «있는» 수**")
