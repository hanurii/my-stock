    P("> ⛔ **원본 " + BQ + "188-mde.py" + BQ + " 는 «건드리지» 않았다** · 셈은 "
      + BQ + "188:84-86" + BQ + " «그대로**")
    P("")
    P("---")
    P("")
    P("# 0. **«왜» 도는가**")
    P("")
    P(F3)
    P("✅ **「1.79」가 «인용 금지» «상태»**다 — **「인용 금지」인 «수» «위»에 «연구의 답»을 «적을» 수 «없다**")
    P("⛔ **「Δ<MDE 는 그대로일 것」이라 «닫으려고»** 도는 게 **«아니다**(유형 106 «점검» 통과)")
    P("")
    P("🔎 **의존이 «풀렸나»**: `188` 의 여덟 짝 = `183` 다섯 + `184` 셋(" + BQ + "188-mde.py:27-37" + BQ + ")")
    P("   ⇒ **«둘» 다 «고쳐» 다시 돌렸다** · **`183` 셋은 «같은» 조건에서도 «바뀌어» «확정»됐다**")
