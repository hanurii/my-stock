# -*- coding: utf-8 -*-
"""판정 ② — 「뒤 구간을 언제 쓸 수 있나」를 «기준»으로 적으려면 수가 무엇이어야 하나.
   그리고 두 세션이 적은 민감도 폭이 서로 다른 것을 검산한다."""
from math import sqrt
Z_OBS, C_CI = 1.826160, 1.645
Z50, Z80 = 1.645, 1.645+0.841621           # 순열 95분위 + 검출력 상수

print("="*78); print("A. 두 세션의 «민감도 폭»이 서로 다르다 — 검산"); print("="*78)
print("  조사 세션 적음 :  73.2 ~ **∞**배      (∞ 는 z95 를 앞 CI 상수와 «묶어서» 나온 값)")
print("  두뇌 세션 적음 :  **31.5** ~ ∞배      ← 재현 안 됨")
for z95 in (1.55, 1.645, 1.83):
    print("     z95=%.3f  →  필요 R = **%6.2f배**" % (z95, (z95/(Z_OBS-C_CI))**2))
print("  ⇒ 맞는 폭 = **73.2 ~ 102.0배**.  🚨 **31.5 는 어떤 z95 로도 안 나온다**(그러려면 z95=1.017)")
print("  ⇒ ∞ 도 틀렸다 — 앞 CI 의 1.645(«신뢰구간 상수»)와 뒤의 z95(«순열 백분위»)는")
print("     **이름만 같고 다른 것**이라 함께 움직이면 안 된다. 묶으면 «없는 특이점»이 생긴다")
print("  ⛔ **보고 전에 «한 곳»에서 고쳐 두 세션이 같은 수를 적어야 한다** (유형 43)")

print(); print("="*78); print("B. 「z 가 얼마면 뒤 구간으로 확인되나」 — 검출력을 «같은 줄»에"); print("="*78)
print("  %-10s %-22s %-22s" % ("검출력", "R=1.81 (폭 «유리»한 끝)", "R=1.15 (폭 «불리»한 끝)"))
for lab, zc in (("50% ", Z50), ("80% ", Z80)):
    row = []
    for r in (1.81, 1.15):
        row.append("앞 z >= **%.3f**" % (C_CI + zc/sqrt(r)))
    print("  %-10s %-22s %-22s" % (lab, row[0], row[1]))
print()
print("  ⇒ 두뇌 세션이 적고 싶어한 「z≈3 이면 있다」는 **표의 «왼쪽 위 한 칸»**이다")
print("     = 검출력 **50%(동전던지기)** · R 을 «유리한 끝»으로 잡은 값")
print("  ⇒ 정직한 기준 = **앞 z ≈ 3.5 ~ 4.0**  (검출력 80%, R 폭 양끝)")
print("  ⇒ 148 관측 1.8262 는 어느 칸에서도 **한참 아래**  ·  148 문턱 2.9856 도 3.49 에 못 미침")
print()
print("  🚨 그리고 이 표는 **N=9 에 매인 값이 아니다** — 앞 문턱과 무관하게 «뒤 자료 크기»만으로 정해진다")
print("     ⇒ 그래서 «기준»으로 적을 수 «있다». 다만 「R=1.81」이 바뀌면 표 전체가 바뀐다")
