"""검증 세션 자기정정 — 「덜 아프다」를 «전부» 지운 것이 과했는지 «110 네 줄 전부»로 다시 본다."""
print("="*78); print("A. 110 §1 수익÷낙폭 — 전체 27.4년  (파라미터 개수를 «같이» 적는다)"); print("="*78)
rows=[("우리(미너비니 −8)",0.204,1,"손절 폭"),("SPY 그냥 보유",0.156,0,"—"),
      ("SPY + 200일선",0.329,1,"🚨 이동평균 «칸 고름»"),("QQQ 그냥 보유",0.128,0,"✅ **유일한 «기준»**"),
      ("QQQ + 200일선",0.199,1,"🚨 «칸 고름»")]
for lab,v,k,note in rows:
    print("  %-20s  **%.3f**   손잡이 %d개   %s" % (lab,v,k,note))
print()
print("  🚨 **우리 0.204  vs  QQQ 그냥 보유 0.128  =  «우리가» %.2f배**" % (0.204/0.128))
print("  ⇒ **파라미터 0 개인 «유일한 기준»에 대해서는 «위험 대비»로 «이깁니다»**")
print("  ⇒ 지는 상대(SPY+200일선 0.329)는 **«칸을 고른» 전략**이다 — 기준이 아니다")

print(); print("="*78); print("B. 110 §2 낙폭 맞춤 — 🚨 **네 줄 «전부»**  (검증 세션은 «지는 두 줄»만 인용했다)"); print("="*78)
w=[("전체 1999~2026",9.37,11.16,"지수 승"),("닷컴 1999~2001",21.39,-1.17,"**미너비니 압승**"),
   ("2002~2017",3.16,5.73,"지수 승"),("2018~2026",17.13,12.74,"**미너비니 승**")]
win=0
for lab,a,b,v in w:
    d=a-b; win += 1 if d>0 else 0
    print("  %-18s 미너비니 %+6.2f%%  vs  지수+손절 %+6.2f%%   차 **%+6.2f%%p**   %s" % (lab,a,b,d,v))
print("\n  ⇒ **%d 대 %d**. 110 자신의 결론은 「지수가 낫다」가 아니라 **«비긴다»에 가깝다**" % (win,4-win))
print("  ⇒ 그리고 **갈림이 «국면»과 붙어 있다** — 성장주가 잘 갈 때 미너비니가 «크게» 이긴다")

print(); print("="*78); print("C. ⛔ 검증 세션 자기정정"); print("="*78)
print("  적은 것  「110 이 «이미 값을 매겼다» → 「덜 아프다」를 «확실»에서 «빼라»」")
print("  🚨 실제  110 은 **2 대 2 · «비긴다»**라 적었다. **나는 지는 두 줄만 인용했다**")
print("  🚨 방향  내가 «선언한» 편향(닫기)과 «같다» — 오늘 «두 번째» 같은 종류다(31.5 판정)")
print("  ✅ 남는 것 — 「낙폭 우위가 «자동으로» 수익 우위가 되지 않는다」는 **여전히 참**")
print("  ✅ 그러나 「덜 아프다」는 **«QQQ 대비»로는 «확실»**이다 (0.204 vs 0.128 = 1.59배)")
