def scan():
    """각본마다 «자리»와 «보유»가 «어느» 단위인지 «세어» 낸다."""
    out = []
    for f in sorted(HERE.glob("*.py")):
        if f.name.startswith("232"):
            continue          # 🚨 «자기참조» 배제 - 검사 각본은 «판»이 아니다(208 때의 그것)
        t = f.read_text(encoding="utf-8", errors="replace")
        if "boot_eq" not in t:
            continue
        lines = t.splitlines()
        pos_all = pos_entry = hold_pos = hold_bar = None
        for i, ln in enumerate(lines, 1):
            if pos_all is None and _re.search(r"all_dates\s*=\s*sorted\(\{d for p in P", ln):
                pos_all = (i, ln.strip())
            if pos_entry is None and (_re.search(r"all_d\s*=\s*sorted\(\{d", ln)
                                      or "sorted(set(entry_dates))" in ln
                                      or _re.search(r"all_dates\s*=\s*sorted\(set\(", ln)):
                pos_entry = (i, ln.strip())
            if hold_pos is None and "pos_of[" in ln and "resolve_date" in ln:
                hold_pos = (i, ln.strip())
            if hold_bar is None and _re.search(r"hold\s*=\s*d\.index\(rd\)", ln):
                hold_bar = (i, ln.strip())
        out.append((f.name, pos_all, pos_entry, hold_pos, hold_bar))
    return out


