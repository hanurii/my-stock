def scan_dropped(limit_from=180):
    """「«세었는데» «버린»」 자리 — «싼» 자로 «훑는다**(⛔ «완전»하지 «않다»)."""
    pat = _re.compile(r"^\s*([A-Za-z_][A-Za-z_0-9]*)\s*=\s*(list|len|set|sorted|Counter)\(")
    files, hits = [], []
    for f in sorted(HERE.glob("*.py")):
        m = _re.match(r"^(\d+)", f.name)
        if not m or int(m.group(1)) < limit_from:
            continue
        if f.name.startswith("238"):
            continue                       # 🚨 «자기참조» 배제
        files.append(f.name)
        txt = f.read_text(encoding="utf-8", errors="replace")
        lines = txt.splitlines()
        prints = "\n".join(ln for ln in lines if _re.search(r"\bP\(|\bprint\(", ln))
        for i, ln in enumerate(lines, 1):
            mm = pat.match(ln)
            if not mm:
                continue
            var = mm.group(1)
            if var.startswith("_"):
                continue
            if _re.search(r"\b%s\b" % _re.escape(var), prints):
                continue                   # 출력에 «나온다** ⇒ «안» 버렸다
            body = "\n".join(lines[i:])
            uses = len(_re.findall(r"\b%s\b" % _re.escape(var), body))
            hits.append((f.name, i, var, uses, ln.strip()[:70]))
    return files, hits


