def bench():
    """벤치마크 시작일 — **«티커» 표에서 «세어» 낸다**(⛔ 손으로 «안» 적음)."""
    out = {}
    if not TZ.exists():
        return out
    with zipfile.ZipFile(TZ) as z:
        with z.open(z.namelist()[0]) as f:
            for row in csv.DictReader(io.TextIOWrapper(f, encoding="utf-8")):
                if row.get("ticker") in ("SPY", "QQQ", "IWM"):
                    out[row["ticker"]] = (row.get("table"), row.get("firstpricedate"),
                                          row.get("lastpricedate"))
    return out


def grab(fn, pat, n=2):
    """결과 문서에서 «줄»을 «그대로» 꺼낸다(파일:줄)."""
    p = RES / fn
    if not p.exists():
        return []
    hits = []
    for i, ln in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
        if pat in ln:
            hits.append((i, ln.strip()))
            if len(hits) >= n:
                break
    return hits


