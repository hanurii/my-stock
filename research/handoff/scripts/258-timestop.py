def eq_of(by_pos, n_pos, slots=5):
    eq, held, got, sday = 1.0, [], 0, 0
    for p in range(n_pos):
        if held:
            keep_ = []
            for hh in held:
                if hh[0] < p:
                    eq += hh[1] * hh[2] / 100
                else:
                    keep_.append(hh)
            held = keep_
        free = slots - len(held)
        cc = by_pos.get(p)
        if free > 0 and cc:
            wgt = eq / slots
            for rel, nt, _k in cc[:free]:
                held.append([p + rel, wgt, nt])
                got += 1
                sday += rel
    for hh in held:
        eq += hh[1] * hh[2] / 100
    return (eq - 1.0) * 100.0, got, sday


def cell_of(lo, hi):
    if lo >= DELTA:
        return "**1**"
    if hi <= -DELTA:
        return "**2**"
    if lo <= 0 <= hi:
        return "**5**"
    if -DELTA <= lo and hi <= DELTA:
        return "**4a**"
    return "**4b**"


def build_both():
    """① 과 Ⓣ 를 «한** 번에 — **`exits` 를 «자른다**(복사본 «없이»)."""
    pairs, miss = m201d.build_pairs(m201d.CANON)
    if pairs is None:
        return None, None, None, miss
    raw = []
    for t, p in pairs:
        r = t["masks"][()]
        epx, d, c = t["entry_px"], p["d"], p["c"]
        rd = r["resolve_date"]
        hold = d.index(rd) if (rd and rd in d) else len(d) - 1
        net = sum(fr * r91.sl.net(round(px / epx * 100 - 100, 2))
                  for _dd, fr, px in r["exits"])
        exs = r["exits"]
        fd = exs[0][0] if exs else rd
        fi = d.index(fd) if (fd and fd in d) else hold
        raw.append((p["code"], t["entry_date"], max(1, hold), net, fi, epx, d, c))
    # ── N★ 유도: **«전체» 거래의 «보유일»** P90 ──
    holds = sorted(x[2] for x in raw)
    nstar = holds[min(len(holds) - 1, int(len(holds) * PCTL))]
    base, arm = [], []
    n_cut = 0
    for cd, ed, hold, net, fi, epx, d, c in raw:
        base.append((cd, ed, hold, net))
        if fi > nstar and nstar < len(d):
            px = c[nstar]
            net1 = r91.sl.net(round(px / epx * 100 - 100, 2))
            arm.append((cd, ed, max(1, nstar), net1))
            n_cut += 1
        else:
            arm.append((cd, ed, hold, net))
    return {C1: base, TT: arm}, nstar, {"cut": n_cut, "holds": holds}, []


