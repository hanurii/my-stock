def hits(pat, where):
    """`grep -rln` 을 «돌려» «맞은» 파일을 «센다** — ⛔ «자기» 파일(248·249)은 «뺀다**."""
    try:
        out = subprocess.run(["grep", "-rlE", pat] + where, cwd=str(HERE.parent),
                             capture_output=True, text=True, encoding="utf-8",
                             errors="replace", timeout=120).stdout
    except Exception:                                # noqa: BLE001
        return []
    fs = [f.strip() for f in out.splitlines() if f.strip()]
    return [f for f in fs if not _re.search(r"/(248|249)", f)]


