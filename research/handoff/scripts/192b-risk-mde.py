def cagr(tot_pct, yrs):
    v = 1.0 + tot_pct / 100.0
    if v <= 1e-9:
        return -100.0
    return (v ** (1.0 / yrs) - 1.0) * 100.0


def ratios(raw, raw_mdd, yrs):
    """씨앗별 «수익÷낙폭». 🚨 낙폭이 0 에 가까우면 비가 «폭발»하므로 «세어»서 적는다."""
    out, blown = [], 0
    for e, m in zip(raw, raw_mdd):
        if abs(m) < 1e-6:
            blown += 1
            continue
        out.append(abs(cagr(e, yrs) / m))
    return out, blown


