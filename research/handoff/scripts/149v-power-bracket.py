"""149a 선행계산에 대한 검증 세션의 «독립» 산출 — 뒤 구간을 열 값어치가 있는가.
쓰는 것 없음. 148 의 공개 수치만 입력으로 쓴다."""
from math import sqrt, erf, log, exp

def Phi(z):  return 0.5*(1.0+erf(z/sqrt(2.0)))
def Phinv(p):
    lo, hi = -12.0, 12.0
    for _ in range(300):
        m=(lo+hi)/2
        if Phi(m) < p: lo=m
        else: hi=m
    return (lo+hi)/2

Z_OBS = 1.826160     # 148 자A +20 (앞 구간, 판정 대상 최대)
THR_B = 1.645        # 뒤 구간 N=1 단측 95%  (순열 95분위의 정규 근사)

print("="*74)
print("① 앞 구간의 1.8262 는 «잡음의 최대»와 구분되는가  — 탐색 크기 k 별")
print("="*74)
for k, lab in ((1,"한 번만 물었다면"), (4,"이 판의 네 칸"), (9,"등록된 시도 N=9"),
               (36,"9 시도 x 4 칸"), (100,"유효 N 은 «못 셈» — 하한 9")):
    emax = Phinv((k-0.375)/(k+0.25))            # 표준정규 최대의 기댓값 근사
    p    = 1.0 - Phi(Z_OBS)**k                  # 귀무에서 최대가 1.8262 이상일 확률
    mark = "**관측이 «아래»**" if Z_OBS < emax else "관측이 위"
    print("  k=%3d %-22s  잡음 최대 기댓값 %.3f  p(max>=1.826)=%.3f   %s"
          % (k, lab, emax, p, mark))
print()
print("  ⇒ k=9 면 «위», k=36 이면 «아래». **탐색 크기를 어떻게 세느냐로 부호가 갈린다**")
print("  ⇒ 「효과 부족이 아니라 아홉 번 시도한 값」은 **k=9 를 «고른» 읽기다**")

print()
print("="*74)
print("② 뒤 구간 검출력 — 뒤/앞 크기비 r 이 «얼마여야» 하나 (z ∝ sqrt(n))")
print("="*74)
rows = (("보정 0 (점추정 그대로)",      Z_OBS),
        ("1σ 내림",                     Z_OBS-1.0),
        ("두뇌 조건1: 단측 95% 하한",   Z_OBS-1.645))
for lab, th in rows:
    if th <= 0:
        print("  %-26s theta=%+.4f  → **어떤 r 로도 검출력이 α 를 못 넘음**" % (lab, th)); continue
    r50 = (THR_B/th)**2
    pw1 = Phi(th*1.0 - THR_B)          # r=1 일 때 검출력
    print("  %-26s theta=%.4f   검출력 50%% 에 필요한 **r = %6.2f 배**   (r=1 이면 검출력 **%4.1f%%**)"
          % (lab, th, r50, 100*pw1))
print()
print("  ⇒ 뒤 구간은 «유보한 조각»이라 r < 1 이 거의 확실하다")
print("  ⇒ **두뇌 세션이 «스스로 고른» 조건 1(단측 95% 하한)을 쓰면 r >= 82 가 필요하다 = 미통과**")
print("  ⇒ 보정을 «0» 으로 놓아야만(=승자의 저주를 «안» 갚아야만) 겨우 동전던지기(57%)가 된다")

print()
print("="*74)
print("③ 유형 40 — 내가 내는 관문의 «통과 예»와 «미통과 예»")
print("="*74)
print("  G1 «가능성»  : 뒤 구간 순열분포에서 «최선의 배치»가 95분위를 넘을 수 있는가")
print("     통과 예   : 뒤 구간 체결일 n>=25 이고 최선 배치 z=2.4 > 95분위 1.70   → 넘을 수 있다")
print("     미통과 예 : n=8 이면 순열 값이 이산이라 최선 배치가 95분위와 «같아» 초과 불가 → 못 넘는다")
print("  G2 «읽기»    : 검출력을 theta 점추정·하한 «둘 다»로 내고 미리 표를 적는가")
print("     통과 예   : 두 수를 다 적고 「50%% 미만이면 미통과 = 못 잼」을 «먼저» 적음")
print("     미통과 예 : 149a 결과를 «본 뒤» 「이 정도면 충분」이라고 적음  ← 유형 24' 재진입")
