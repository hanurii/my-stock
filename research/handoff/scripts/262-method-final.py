def rule_of(stem):
    """각본이 «박은» 규칙값 · 정본을 «읽는지» — 파일을 «열어» 본다."""
    f = HERE / (stem + ".py")
    if not f.exists():
        return None, None, "각본 없음"
    t = f.read_text(encoding="utf-8")
    body = "\n".join(ln for ln in t.splitlines() if not ln.lstrip().startswith("#"))
    m = RULE_RE.search(body)
    pinned = None
    if m:
        v = [x.strip() for x in m.group(1).split(",") if x.strip()]
        head = body[m.start():m.start() + 40]
        pinned = ((v[1], v[0]) if head.startswith("STOP") else (v[0], v[1]))
    reads = bool(re.search(r"r91\.(TARGET|STOP)|201d-rs-threshold|91-us-out-of-sample", body))
    grid = bool(re.search(r"^TARGETS *=|^STOPS *=", body, re.M))
    md = HERE.parent / "results" / (stem + ".md")
    if not md.exists():
        for alt in (stem.split("-")[0], stem.replace("-fixed", "")):
            g = sorted((HERE.parent / "results").glob(alt + "*.md"))
            if g:
                md = g[0]
                break
    when = "?"
    if md.exists():
        import datetime as dt
        when = dt.datetime.fromtimestamp(md.stat().st_mtime).strftime("%Y-%m-%d")
    return pinned, (grid, reads), when


