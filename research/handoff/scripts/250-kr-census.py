def yield_row(tag, title, buf, cls, tally):
    body = "\n".join(buf)
    nums = set(_re.findall(r"`(\d+[a-z]*)[-`]", body)) | set(_re.findall(r"`(\d+[a-z]*)`", body))
    mk = Counter()
    for n in nums:
        for f, k in cls.items():
            if _re.match(r"^%s-" % _re.escape(n), f):
                mk[k] += 1
                break
    if not mk:
        v = "⚪ 판정불가"
    elif mk.get("🇰🇷 한국", 0) and mk.get("🇺🇸 미국", 0):
        v = "🟡 섞임"
    elif mk.get("🇰🇷 한국", 0) or (mk.get("🟡 섞임", 0) and not mk.get("🇺🇸 미국", 0)):
        v = "🇰🇷 한국"
    elif mk.get("🟡 섞임", 0):
        v = "🟡 섞임"
    else:
        v = "🇺🇸 미국"
    tally[tag][v] += 1
    P("| §%s | %s | %s | %s |" % (tag, title[:40], " ".join(sorted(nums)[:6]) or "—", v))


