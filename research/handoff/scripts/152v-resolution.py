"""152 설계 반론 — 「못 가린다」면 «몇 년»이 필요한가. 그리고 «이기는 비교»에도 대는가."""
from math import sqrt
Z95, Z80 = 1.959964, 0.841621
CASES=[("우리 vs QQQ (27.4년)",1.23,27,"짐"),("우리 vs SPY (27.4년)",0.73,27,"이김"),
       ("우리 vs SPY (표본밖 15.66년)",3.88,16,"짐")]
print("="*80); print("A. ★ 진짜 산출은 CI 가 아니라 «몇 년이 필요한가»다 (검출력 80%)"); print("="*80)
print("  %-30s %-6s %-26s" % ("비교","격차","필요 연수 (SD=15 / 20 / 25%p)"))
for lab,g,n,side in CASES:
    ys=[((Z95+Z80)*sd/g)**2 for sd in (15.,20.,25.)]
    print("  %-30s %5.2f  %8.0f년 / %8.0f년 / %8.0f년   (%s)" % (lab,g,ys[0],ys[1],ys[2],side))
print()
print("  ⇒ **1.23%p 를 «자료로» 가리려면 SD=20%p 에서 «약 2,000년»**이 필요하다")
print("  ⇒ 149 의 「114년」과 «같은 종류»의 답 — **물음이 자료보다 크다**")

print(); print("="*80); print("B. 🚨 대칭 검사 — 「못 가린다」는 «이기는 비교»도 죽인다"); print("="*80)
for lab,g,n,side in CASES:
    need = g*sqrt(n)/Z95
    print("  %-30s 필요 SD **%5.2f%%p**  (현실 15~25)  →  «%s»는 %s"
          % (lab, need, side, "**못 가린다**"))
print()
print("  ⇒ **「우리가 SPY 를 이긴다」(0.73%p)가 «제일 먼저» 죽는다**(필요 SD 1.94)")
print("  ⇒ **152 는 «우리 편»이 아니다. 그게 이 판정이 «호의»가 아니라는 증거다**")

print(); print("="*80); print("C. 91 의 자 vs 152 의 자 — 무엇이 다른가"); print("="*80)
print("  91  MDE **0.535%p**  = «우리 규칙의 운»(씨앗 20판) — 같은 15.66년을 다시 돌린 변동")
print("  152 필요 SD **7.92%p** = «시장의 운»(다른 15.66년이었다면)         →  **15배**")
print("  ⇒ 둘은 «다른 물음»이고 **둘 다 맞다**. 틀린 건 «어느 쪽을 «결정»에 쓰느냐»다")
print("  ⇒ 사용자는 «앞으로»를 정한다 → **결정에 쓰는 자는 152 쪽**이다")
