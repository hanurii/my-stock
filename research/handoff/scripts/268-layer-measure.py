r"""268 - **넉넉한 문턱 «실측» ＋ 소비자가 «읽는» 키 «전수»** (조사 세션 2026-09-10)

  ⛔ **«짓지» 않았다.** «재기»만이다.

  🔴 **두뇌가 «고쳐» 준 것**: 「고정 날짜 문턱 ＋ 여유 10일」을 «버리고» —
     **넉넉히 자른 뒤 종목마다 «마지막» 310봉으로 «다듬는다»**.
     ⇒ ★ **「몇 개월이면 되나」를 «고를» 필요가 «사라진다»**(`255` k★ 와 «같은» 결).

  💰 **어림을 «바닥»에서 «곱했다»**(내 진단대로): 53.3초 중 «줄 읽기»가 바닥이고
     파싱은 4.37%에만 든다 ⇒ 24개월이면 남는 행 «2배» ⇒ **60~80초**로 봤다.
     🔴 **실제 «중앙» 54.3초** — **«또» 과대**다. 열 번 중 «아홉» 번.
     ⇒ ★★ **까닭이 «드러났다»**: **«바닥»이 «내가 생각한 것보다 «훨씬» 크다** —
        4,530만 줄을 «읽는» 것이 «거의» 전부이고 **파싱 몫은 «거의» «안** 보인다**.
        ⇒ ⇒ **「곱하기」도 «틀렸다». «곱할» 것이 «없었다».**

실행: PYTHONIOENCODING=utf-8 PYTHONUTF8=1 python research/handoff/scripts/268-layer-measure.py
"""
from __future__ import annotations

import sys

sys.stdout.reconfigure(encoding="utf-8")
P = print
BQ = chr(96)
F3 = BQ * 3
PCT = chr(37)

# 소비자가 «읽는» 키 — grep 으로 «전수» 확인한 것(범위를 아래 본문에 적는다)
KEYS = (
    ("dates", "vcp · power_play · cheat · screen_trend_template", True),
    ("opens", "vcp", True),
    ("highs", "vcp · power_play · cheat", True),
    ("lows", "vcp · power_play · cheat", True),
    ("closes", "vcp · power_play · cheat · screen_trend_template", True),
    ("volumes", "vcp · power_play · cheat", True),
    ("timestamps", "screen_trend_template.py:96", True),
    ("foreign_rates", "ohlcv_matrix.get_foreign — 한국 전용", False),
)

M = {
    "cut": "2024-09-01", "keep": 310,
    "runs": (66.1, 54.3, 51.7), "med": 54.3,
    "rows_kept": 3110630, "rows_tot": 45317834, "tickers": 7398,
    "pre_med": 506, "pre_max": 506,
    "trim": 26.3, "have310": 5858,
    "w": (4.8, 4.5, 7.9), "r": (3.5, 2.8, 8.4), "wm": 4.8, "rm": 3.5, "mb": 114,
    "prev_sec": 53.3, "prev_tick": 6905,
}


def main() -> int:
    P("# 268 - 넉넉히 자르고 다듬기, 그리고 읽는 키 전수")
    P("")
    P("> 조사 세션 2026-09-10 · " + BQ
      + "research/handoff/scripts/268-layer-measure.py" + BQ)
    P("> 아무것도 짓지 않았다. 재기만 했다.")
    P("")
    P("---")
    P("")

    # ── 1 ────────────────────────────────────────────
    P("## 1. 소비자가 읽는 키 — 전수로 셌다")
    P("")
    P("찾은 범위를 먼저 적는다.")
    P("")
    P("```")
    P("scripts/screen_trend_template.py")
    P("scripts/canslim_lib/trend_template.py")
    P("scripts/canslim_lib/vcp.py · power_play.py · cheat.py · ipo_track.py")
    P("```")
    P("")
    P("검출기 셋은 `series.get(\"...\")` 로 꺼내고, 화면 스크립트는 `mtx[\"...\"]` 로 읽는다.")
    P("추세 판별기와 IPO 트랙은 series 를 통째로 받지 않고 리스트를 인자로 받는다.")
    P("")
    P("| 키 | 누가 읽나 | 만들어야 하나 |")
    P("|---|---|---|")
    for k, who, need in KEYS:
        P("| `%s` | %s | %s |" % (k, who, "**예**" if need else "아니오 — 빈 리스트로 둔다"))
    P("")
    P(F3)
    P("만들어야 할 키는 일곱이다.")
    P("dates · opens · highs · lows · closes · volumes · timestamps")
    P("")
    P("foreign_rates 는 한국 전용이라 빈 리스트로 둔다.")
    P(F3)
    P("")
    P("앞선 실측에서 `timestamps` 를 빠뜨렸다. 이번에는 넣고 쟀다.")
    P("")

    # ── 2 ────────────────────────────────────────────
    P("---")
    P("")
    P("## 2. 넉넉히 자르고 다듬기 — 실측")
    P("")
    P("고정 날짜 문턱을 버렸다. 24개월치를 넉넉히 자른 뒤")
    P("종목마다 마지막 %d봉만 남기는 방식이다." % M["keep"])
    P("그러면 「몇 개월이면 되나」를 고를 일이 없어진다.")
    P("")
    P("| 무엇 | 값 |")
    P("|---|---|")
    P("| 날짜 문턱 | %s (24개월) |" % M["cut"])
    P("| 남긴 행 | %s / %s (%.2f%s) |"
      % (format(M["rows_kept"], ","), format(M["rows_tot"], ","),
         100.0 * M["rows_kept"] / M["rows_tot"], PCT))
    P("| 종목 수 | %s |" % format(M["tickers"], ","))
    P("| 다듬기 전 종목당 봉 | 중앙 %d · 최대 %d |" % (M["pre_med"], M["pre_max"]))
    P("| **추리기 (세 번 중앙)** | **%.1f초** |" % M["med"])
    P("| **다듬기 + timestamps** | **%.1f초** |" % M["trim"])
    P("")
    P("세 번 값은 %s 초였다. 중앙을 쓴다."
      % " · ".join("%.1f" % x for x in M["runs"]))
    P("")
    P(F3)
    P("여유가 %d봉이다. 필요한 것이 %d 이므로 %d봉이 남는다."
      % (M["pre_max"], M["keep"], M["pre_max"] - M["keep"]))
    P("휴장일이 얼마나 끼든 모자랄 일이 없다.")
    P(F3)
    P("")
    P("### 뜻밖의 것 — 문턱을 넓혀도 시간이 안 늘었다")
    P("")
    P("| 문턱 | 남긴 행 | 종목 | 추리기 |")
    P("|---|---:|---:|---:|")
    P("| 2025-06-01 (12개월) | 1,979,932 (4.37%s) | %s | %.1f초 |"
      % (PCT, format(M["prev_tick"], ","), M["prev_sec"]))
    P("| %s (24개월) | %s (%.2f%s) | %s | %.1f초 |"
      % (M["cut"], format(M["rows_kept"], ","),
         100.0 * M["rows_kept"] / M["rows_tot"], PCT,
         format(M["tickers"], ","), M["med"]))
    P("")
    P("남긴 행이 1.6배가 됐는데 시간은 같다.")
    P("병목이 파싱이 아니라 4,530만 줄을 읽어 내려가는 것 자체이기 때문이다.")
    P("")
    P("이건 내 어림이 왜 계속 틀리는지도 말해 준다.")
    P("나는 60~80초로 봤다. 바닥을 재고 곱하는 쪽으로 바꿨는데도 과대였다.")
    P("곱할 것이 거의 없었던 것이다. 열 번 중 아홉 번을 과대로 잡았다.")
    P("")
    P("### 다듬기가 생각보다 비싸다")
    P("")
    P("다듬기와 timestamps 만들기에 %.1f초가 든다. 추리기의 절반이다." % M["trim"])
    P("날짜 문자열마다 `time.strptime` 을 부르기 때문이다.")
    P("날짜가 종목마다 겹치므로 한 번만 바꿔 두고 돌려쓰면 줄어들 것이다.")
    P("그건 어림이다. 재지 않았고 고치지도 않았다.")
    P("")

    # ── 3 ────────────────────────────────────────────
    P("---")
    P("")
    P("## 3. 저장 — json 한 덩어리")
    P("")
    P("| 무엇 | 값 |")
    P("|---|---|")
    P("| 디스크 | **%d MB** |" % M["mb"])
    P("| 쓰기 (세 번 중앙) | %.1f초 |" % M["wm"])
    P("| 읽기 (세 번 중앙) | %.1f초 |" % M["rm"])
    P("")
    P("세 번씩 쟀다. 쓰기 %s 초, 읽기 %s 초였다."
      % (" · ".join("%.1f" % x for x in M["w"]),
         " · ".join("%.1f" % x for x in M["r"])))
    P("")
    P("마지막 한 번이 다른 둘보다 두 배 가까이 느렸다.")
    P("같은 코드로 같은 자료를 잰 것이므로 기계 쪽 사정이다.")
    P("한 번만 쟀다면 이걸 못 봤을 것이다.")
    P("")
    P("앞선 판에서 json 이 pickle 보다 작고 빠르다고 적었는데,")
    P("그건 한 번씩만 잰 값이었다. 이번 세 번으로 보면 편차가 그 차이만큼 크다.")
    P("그러니 「json 이 더 빠르다」는 이 수로는 말할 수 없다.")
    P("작다는 것은 그대로다.")
    P("")

    # ── 4 ────────────────────────────────────────────
    P("---")
    P("")
    P("## 4. 310봉을 채우는 종목")
    P("")
    P("| 무엇 | 값 |")
    P("|---|---|")
    P("| 310봉을 채운 종목 | %s / %s (%.1f%s) |"
      % (format(M["have310"], ","), format(M["tickers"], ","),
         100.0 * M["have310"] / M["tickers"], PCT))
    P("| 못 채우는 종목 | %s |" % format(M["tickers"] - M["have310"], ","))
    P("")
    P("12개월 문턱에서는 79.9%s 였고 24개월 문턱에서는 %.1f%s 다."
      % (PCT, 100.0 * M["have310"] / M["tickers"], PCT))
    P("비율이 거의 같다. 문턱을 넓혀도 못 채우는 종목은 그대로다.")
    P("창이 짧아서가 아니라 그 종목들이 짧기 때문이다.")
    P("")
    P("종목 수는 %s 에서 %s 으로 늘었다. 창이 길어지며 그 안에서 상장폐지된 것이 더 들어왔다."
      % (format(M["prev_tick"], ","), format(M["tickers"], ",")))
    P("신규 상장인지 상장폐지인지 가르는 것은 유니버스 판의 일이라 여기서 안 했다.")
    P("")
    P("## 이 판이 못 한 것")
    P("")
    P("- `time.strptime` 을 한 번만 부르게 고치면 얼마나 빨라지는지 안 쟀다.")
    P("- pickle 을 세 번으로 다시 재지 않았다. json 쪽만 세 번 쟀다.")
    P("- 야후 꼬리를 어떻게 붙일지는 이 판 밖이다.")
    P("- 못 채우는 %s개를 신규와 상폐로 안 갈랐다."
      % format(M["tickers"] - M["have310"], ","))
    P("- 24개월이 넉넉하다는 것은 오늘 자료 기준이다. 다음에 다시 재야 한다.")
    P("")
    P("커밋은 두뇌 몫입니다.")
